#!/usr/bin/env python3
"""Generate the JP symbol inputs from the USA names and the US/JP function map.

configs/JP/sym.main.txt           splat input: one function name per JP address
linkers/JP/undefined_syms_manual.txt  linker aliases: extra names for the same
                                      addresses, data symbols (jp_data_map.py) and
                                      the translated USA manual symbols.
Usage: jp_make_syms.py <us main.exe> <jp exe> [<nm -n of the USA main.elf>]
"""
import csv, re, subprocess, sys, tempfile, os

fmap, cnames = {}, []
for r in csv.DictReader(open("docs/us_jp_function_map.csv")):
    if r["jp_address"]: fmap[int(r["address"], 16)] = int(r["jp_address"], 16); cnames.append((r["name"], int(r["jp_address"], 16)))
split, alias, seen_addr, seen_name = ["// JP (SLPS-012.30) function names carried over from the USA build (tools/scripts/jp_make_syms.py).", ""], [], {}, set()
for l in open("configs/USA/sym.main.txt"):
    m = re.match(r"\s*(\w+)\s*=\s*0x([0-9A-Fa-f]+);\s*//\s*type:func", l)
    if not m or int(m.group(2), 16) not in fmap: continue
    ja = fmap[int(m.group(2), 16)]; n = m.group(1)
    if ja in seen_addr: alias.append(f"{n} = 0x{ja:08X};")
    else: seen_addr[ja] = n; split.append(f"{n} = 0x{ja:08X}; // type:func")
    seen_name.add(n)
split.append("_ramsize = 0x8009C838; // size:0x4"); seen_name.add("_ramsize")
# asm that calls a function now compiled from C needs the name even though no asm label defines it
for l in split[2:]:
    m = re.match(r"(\w+) = (0x\w+);", l)
    if m: alias.append(f"{m.group(1)} = {m.group(2)};")
open("configs/JP/sym.main.txt", "w").write("\n".join(split) + "\n")

import importlib.util
spec = importlib.util.spec_from_file_location('jdm', 'tools/scripts/jp_data_map.py'); jdm = importlib.util.module_from_spec(spec); spec.loader.exec_module(jdm)
best = jdm.compute(sys.argv[1], sys.argv[2])
tmp = tempfile.mktemp()
subprocess.check_call([sys.executable, "tools/scripts/jp_data_map.py", sys.argv[1], sys.argv[2], tmp], stdout=subprocess.DEVNULL)
for l in open(tmp):
    m = re.match(r"(\w+) = (0x\w+);", l)
    if m and m.group(1) not in seen_name: seen_name.add(m.group(1)); alias.append(l.strip())
os.unlink(tmp)
for l in open("configs/JP/function_overrides.csv"):
    if l.strip() and not l.startswith("#"):
        n, a = l.strip().split(",")
        if not n.startswith("func_"): cnames.append((n, int(a, 16)))     # func_ rows are for jp_port_c.py
for n, ja in cnames:
    if n not in seen_name and not n.startswith(("func_", "D_")): seen_name.add(n); alias.append(f"{n} = 0x{ja:08X};")

if len(sys.argv) > 3:                       # every other USA global the pairing located
    for l in open(sys.argv[3]):
        p = l.split()
        if len(p) == 3 and p[1] in "bBdDsSCrR" and p[2] not in seen_name and not re.match(r"(D|func|jtbl|jlabel|L)_", p[2]) and "." not in p[2] and "$" not in p[2]:
            a = int(p[0], 16)
            if a in best: seen_name.add(p[2]); alias.append(f"{p[2]} = 0x{best[a]:08X};")
# USA manual aliases: `NAME = 0xADDR;` or `NAME = other;`
byaddr = {}
for l in open("configs/JP/sym.main.txt"):
    m = re.match(r"(\w+) = (0x\w+);", l)
    if m: byaddr[m.group(1)] = m.group(2)
for l in open("linkers/USA/undefined_syms_manual.txt"):
    m = re.match(r"\s*(\w+)\s*=\s*(\w+);", l)
    if not m or m.group(1) in seen_name: continue
    v = m.group(2)
    if v.startswith("0x"): continue            # raw USA addresses have no JP meaning here
    mm = re.match(r"(?:D|func|jtbl|jlabel)_([0-9A-Fa-f]{8})$", v)
    if mm:
        ja = best.get(int(mm.group(1), 16)) or fmap.get(int(mm.group(1), 16))
        if ja is None: continue
        v = f"0x{ja:08X}"
    seen_name.add(m.group(1)); alias.append(f"{m.group(1)} = {v};")
open("linkers/JP/undefined_syms_manual.txt", "w").write("/* Generated by tools/scripts/jp_make_syms.py. */\n" + "\n".join(alias) + "\n")
print(len(split) - 2, "names,", len(alias), "aliases")
